function copiarCorreo(correo) {
    // API moderna del navegador para copiar al portapapeles
    navigator.clipboard.writeText(correo).then(function() {
        // Alerta elegante confirmando la acción
        Swal.fire({
            icon: 'success',
            title: '¡Correo copiado!',
            html: `La dirección <strong>${correo}</strong> está lista para pegarse.`,
            timer: 2500, // Se cierra sola en 2.5 segundos
            timerProgressBar: true,
            showConfirmButton: false,
            toast: true, // Estilo notificación pequeña
            position: 'top-end' // Aparece en la esquina superior derecha
        });
    }).catch(function(err) {
        console.error('Error al intentar copiar el correo: ', err);
        Swal.fire({
            icon: 'error',
            title: 'Oops...',
            text: 'No se pudo copiar el correo automáticamente.'
        });
    });
}
</script>